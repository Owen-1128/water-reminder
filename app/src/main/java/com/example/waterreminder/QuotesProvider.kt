package com.example.waterreminder

import java.util.Calendar

/**
 * 深意提示语库。
 * 每一条都试图把「喝水」这件小事，连接到生活、自省与温柔的坚持。
 * quoteFor(hour) 会根据「日期 + 小时」稳定地轮换，保证同一时刻提示语一致，
 * 同时每天、每小时都有所变化。
 */
object QuotesProvider {

    private val quotes = listOf(
        "上善若水，水善利万物而不争——也请温柔地善待自己的身体。",
        "你忙着赶路，别让身体在半途干涸。",
        "一杯温水，是成年世界里最朴素的自我照顾。",
        "身体约七成是水，及时补给，才装得下明天的风。",
        "滴水穿石，是坚持的力量；每日饮水，是温柔的坚持。",
        "水至清则无鱼，人至疲则易病；累了，先喝口水。",
        "喝水这件小事，藏着你对自己最安静的在意。",
        "别等口渴才想起水，就像别等失去才懂得珍惜。",
        "把杯子端起来的那一刻，你也在认真对待此刻的自己。",
        "水不争高下，却能润泽万物；好好喝水，也是一种成全。",
        "一天的清醒，往往从一杯水开始。",
        "你照顾了那么多人和事，也别忘了照顾这副身体。",
        "慢一点，喝口水，世界不会因为你停这三秒而崩塌。",
        "水是最便宜的药，却最容易被遗忘。",
        "每一次吞咽，都是身体在轻声说「谢谢」。",
        "焦躁的时候，先喝口水——水能平息的，不止是口渴。",
        "把喝水变成仪式，把健康过成日常。",
        "你不需要惊天动地，按时喝杯水就很了不起。",
        "水流千里归大海，人走万里要续航；补水，即是续命。",
        "真正的自律，是把最简单的事，认真做一辈子。",
        "愿你的日子，像水一样清澈，也像水一样源源不断。",
        "提醒自己喝水，其实是提醒自己：我还值得被好好对待。",
        "水满则溢，人累则歇；喝口水，也顺便歇一歇。",
        "这一口，敬认真生活的你。"
    )

    /** 根据「日 + 小时」稳定取一句，今日每小时不同、每天也不同。 */
    fun quoteFor(hour: Int): String {
        val day = Calendar.getInstance().get(Calendar.DAY_OF_YEAR)
        return quotes[(day * 24 + hour).mod(quotes.size)]
    }

    /** 随机取一句（用于测试通知）。 */
    fun randomQuote(): String {
        return quotes[(System.currentTimeMillis() / 60000L).toInt().mod(quotes.size)]
    }
}
